#!/usr/bin/env bash
# Writes the Homebrew formula and the Scoop manifest for a release from its
# checksums.txt, into OUTDIR/Formula/vnsalary.rb and OUTDIR/bucket/vnsalary.json
# (the layout of the HuynhNhatKhanh/homebrew-tap repository).
# Usage: scripts/package-manifests.sh vX.Y.Z path/to/checksums.txt OUTDIR
set -euo pipefail

version="${1:?usage: $0 vX.Y.Z checksums.txt OUTDIR}"
checksums="${2:?usage: $0 vX.Y.Z checksums.txt OUTDIR}"
outdir="${3:?usage: $0 vX.Y.Z checksums.txt OUTDIR}"
case "$version" in v[0-9]*.[0-9]*.[0-9]*) ;; *) echo "version must look like vX.Y.Z: $version" >&2; exit 1 ;; esac

repo="https://github.com/HuynhNhatKhanh/vnsalary"
base="$repo/releases/download/$version"

# sha FILE prints the SHA-256 of a release archive, failing if it is missing.
sha() {
  local s
  s=$(awk -v f="$1" '$2 == f {print $1}' "$checksums")
  if [ -z "$s" ]; then echo "no checksum for $1 in $checksums" >&2; exit 1; fi
  echo "$s"
}

name() { echo "vnsalary_${version}_$1"; }

# Look every checksum up first: a failure inside the heredocs below would only
# end a subshell and leave an empty sha256 in the output.
declare -A hash
for target in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
  hash[$target]=$(sha "$(name "$target").tar.gz")
done
for target in windows_amd64 windows_arm64; do
  hash[$target]=$(sha "$(name "$target").zip")
done

mkdir -p "$outdir/Formula" "$outdir/bucket"

cat > "$outdir/Formula/vnsalary.rb" <<RUBY
# Generated by scripts/package-manifests.sh in $repo; do not edit by hand.
class Vnsalary < Formula
  desc "Vietnam gross/net salary, PIT and social insurance calculator"
  homepage "$repo"
  version "${version#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/$(name darwin_arm64).tar.gz"
      sha256 "${hash[darwin_arm64]}"
    end
    on_intel do
      url "$base/$(name darwin_amd64).tar.gz"
      sha256 "${hash[darwin_amd64]}"
    end
  end

  on_linux do
    on_arm do
      url "$base/$(name linux_arm64).tar.gz"
      sha256 "${hash[linux_arm64]}"
    end
    on_intel do
      url "$base/$(name linux_amd64).tar.gz"
      sha256 "${hash[linux_amd64]}"
    end
  end

  def install
    bin.install "vnsalary"
  end

  test do
    assert_match "vnsalary $version", shell_output("#{bin}/vnsalary version")
  end
end
RUBY

cat > "$outdir/bucket/vnsalary.json" <<JSON
{
    "version": "${version#v}",
    "description": "Vietnam gross/net salary, PIT and social insurance calculator",
    "homepage": "$repo",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "$base/$(name windows_amd64).zip",
            "hash": "${hash[windows_amd64]}",
            "extract_dir": "$(name windows_amd64)"
        },
        "arm64": {
            "url": "$base/$(name windows_arm64).zip",
            "hash": "${hash[windows_arm64]}",
            "extract_dir": "$(name windows_arm64)"
        }
    },
    "bin": "vnsalary.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$repo/releases/download/v\$version/vnsalary_v\$version_windows_amd64.zip",
                "extract_dir": "vnsalary_v\$version_windows_amd64"
            },
            "arm64": {
                "url": "$repo/releases/download/v\$version/vnsalary_v\$version_windows_arm64.zip",
                "extract_dir": "vnsalary_v\$version_windows_arm64"
            }
        },
        "hash": {
            "url": "$repo/releases/download/v\$version/checksums.txt"
        }
    }
}
JSON

echo "wrote $outdir/Formula/vnsalary.rb and $outdir/bucket/vnsalary.json"
